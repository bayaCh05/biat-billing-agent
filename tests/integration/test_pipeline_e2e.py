class TestLifecycleE2E:

    def test_mark_paid_advances_supplier_invoice(self, tmp_dirs, repository):
        pdf_path = make_supplier_invoice_pdf(tmp_dirs / "inbox" / "pay_001.pdf")
        components = _build_components(repository, str(tmp_dirs / "exports"), _SUPPLIER_LLM_RESPONSE)

        invoice = _make_invoice_record(pdf_path)
        repository.save(invoice)
        process_invoice(invoice, components)

        saved = repository.get_by_id(invoice.id)
        if saved.status not in (InvoiceStatus.EXPORTED, InvoiceStatus.VALIDATED):
            pytest.skip(f"Invoice in unexpected status {saved.status} — check validation flags")

        # Manually move to EXPORTED for this test
        saved.status = InvoiceStatus.EXPORTED
        repository.save(saved)

        from src.suivi.lifecycle_tracker import LifecycleTracker
        tracker = LifecycleTracker(repository=repository)
        paid = tracker.mark_paid(
            invoice_id=invoice.id,
            payment_reference="VIR-2024-001",
            amount=1785.0,
        )

        assert paid.status == InvoiceStatus.PAID
        assert paid.paid_at is not None

        db_paid = repository.get_by_id(invoice.id)
        assert db_paid.status == InvoiceStatus.PAID

    def test_aggregator_snapshot_reflects_pipeline_state(self, tmp_dirs, repository):
        pdf_path = make_supplier_invoice_pdf(tmp_dirs / "inbox" / "agg_001.pdf")
        components = _build_components(repository, str(tmp_dirs / "exports"), _SUPPLIER_LLM_RESPONSE)

        invoice = _make_invoice_record(pdf_path)
        repository.save(invoice)
        process_invoice(invoice, components)

        agg = Aggregator(repository=repository)
