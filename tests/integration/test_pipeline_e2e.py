# ── Duplicate detection E2E ───────────────────────────────────────────────────

class TestDuplicateDetectionE2E:

    def test_second_identical_invoice_flagged_as_duplicate(self, tmp_dirs, repository):
        components = _build_components(repository, str(tmp_dirs / "exports"), _SUPPLIER_LLM_RESPONSE)

        # First invoice goes through fine
        pdf1 = make_supplier_invoice_pdf(tmp_dirs / "inbox" / "dup_first.pdf")
        inv1 = _make_invoice_record(pdf1)
        repository.save(inv1)
        process_invoice(inv1, components)
        saved1 = repository.get_by_id(inv1.id)
        first_status = saved1.status

        # Second invoice with same number from same issuer
        pdf2 = make_supplier_invoice_pdf(tmp_dirs / "inbox" / "dup_second.pdf")
        inv2 = InvoiceRecord(
            file_hash=sha256(str(pdf2)) + "_alt",  # different hash (different file)
            raw_file_path=str(pdf2),
            status=InvoiceStatus.RECEIVED,
        )
        repository.save(inv2)
        process_invoice(inv2, components)
        saved2 = repository.get_by_id(inv2.id)

        # Must be flagged (FLAGGED or ERROR) due to duplicate detection
        flag_types = [f.flag_type for f in saved2.flags]
        assert FlagType.DUPLICATE in flag_types
        assert saved2.status in (InvoiceStatus.FLAGGED, InvoiceStatus.ERROR)


