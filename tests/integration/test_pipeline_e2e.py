# ── Recovery E2E ─────────────────────────────────────────────────────────────

class TestRecoveryE2E:

    def test_recovery_resets_mid_flight_invoices(self, tmp_dirs, repository):
        """Invoices stuck in EXTRACTING are reset to RECEIVED on agent startup."""
        stuck = InvoiceRecord(
            file_hash="stuck_hash",
            raw_file_path="/tmp/stuck.pdf",
            status=InvoiceStatus.EXTRACTING,
        )
        repository.save(stuck)

        recover_interrupted(repository)

        recovered = repository.get_by_id(stuck.id)
        assert recovered.status == InvoiceStatus.RECEIVED

    def test_recovery_re_enqueues_received_invoices(self, tmp_dirs, repository):
        received = InvoiceRecord(
            file_hash="received_hash",
            raw_file_path="/tmp/received.pdf",
            status=InvoiceStatus.RECEIVED,
        )
        repository.save(received)

        mock_ingestor = MagicMock()
        re_enqueue_received(repository, mock_ingestor)

        mock_ingestor.enqueue.assert_called_once()
        args = mock_ingestor.enqueue.call_args[0]
        assert args[0].id == received.id
