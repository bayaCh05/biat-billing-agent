def _build_components(repository, export_path: str, llm_response: str) -> PipelineComponents:
    """Build PipelineComponents with a mocked LLM backend."""
    cfg = dict(_CONFIG)
    cfg["storage"] = dict(cfg["storage"], export_path=export_path)

    class _MockBackend(LLMBackendBase):
        def complete(self, system: str, user: str) -> str:
            return llm_response

    extractor = HybridExtractor(
        pdf_reader=PDFReader(
            min_chars=cfg["extraction"]["min_native_pdf_chars"],
            min_quality_ratio=cfg["extraction"]["min_text_quality_ratio"],
        ),
        preprocessor=OCRPreprocessor(),
        ocr_engine=TesseractEngine(languages=["fr"]),
        llm_extractor=LLMExtractor(
            backend=_MockBackend(),
            languages=cfg["extraction"]["languages"],
            mode="full_schema",   # mock returns full schema; production uses amounts_only
        ),
        config=cfg,
    )

    catalog = CostCatalog.from_yaml("config/cost_catalog.yaml")
    journal_repository = JournalRepository(repository.session)

    return PipelineComponents(
        extractor=extractor,
        classifier=Classifier(rules=_CLASSIFICATION_RULES),
        coder=AccountingCoder(catalog=catalog),
        field_validator=FieldValidator(
            confidence_thresholds=cfg["extraction"]["confidence_thresholds"]
        ),
        coherence_checker=CoherenceChecker(config=cfg),
        duplicate_detector=DuplicateDetector(config=cfg, repository=repository),
        anomaly_detector=AnomalyDetector(config=cfg, repository=repository),
        auto_corrector=AutoCorrector(config=cfg, repository=repository),
        exporter=JSONExporter(export_path=export_path),
        entry_generator=EntryGenerator(),
        cost_catalog=catalog,
        repository=repository,
        journal_repository=journal_repository,
        max_retries=cfg["agent"]["max_retry_attempts"],
    )


def _make_invoice_record(file_path: Path) -> InvoiceRecord:
    return InvoiceRecord(
        file_hash=sha256(str(file_path)),
        raw_file_path=str(file_path),
        status=InvoiceStatus.RECEIVED,
    )


